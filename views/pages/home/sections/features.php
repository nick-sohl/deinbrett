<script>
(function () {
  var slider   = document.getElementById('gallery-slider');
  var track    = document.getElementById('gallery-track');
  var progress = document.getElementById('gallery-progress');
  var dots     = slider ? slider.querySelectorAll('.gallery-dot') : [];
  if (!slider || !track) return;

  var count    = dots.length;
  var current  = 0;
  var duration = 3800; // ms per slide
  var timer, progressTimer, progressStart;

  function goTo(n) {
    current = (n + count) % count;
    track.style.transform = 'translateX(-' + (current * 100) + '%)';
    dots.forEach(function (d, i) {
      d.classList.toggle('gallery-dot--active', i === current);
    });
    startProgress();
  }

  function startProgress() {
    clearInterval(progressTimer);
    if (progress) progress.style.transition = 'none';
    if (progress) progress.style.width = '0%';
    progressStart = Date.now();
    requestAnimationFrame(function () {
      if (progress) {
        progress.style.transition = 'width ' + duration + 'ms linear';
        progress.style.width = '100%';
      }
    });
  }

  function startAuto() {
    clearInterval(timer);
    timer = setInterval(function () { goTo(current + 1); }, duration);
  }

  // Touch / swipe support
  var touchStartX = 0;
  slider.addEventListener('touchstart', function (e) {
    touchStartX = e.touches[0].clientX;
    clearInterval(timer);
    clearInterval(progressTimer);
    if (progress) { progress.style.transition = 'none'; }
  }, { passive: true });

  slider.addEventListener('touchend', function (e) {
    var dx = e.changedTouches[0].clientX - touchStartX;
    if (Math.abs(dx) > 40) goTo(current + (dx < 0 ? 1 : -1));
    startAuto();
  }, { passive: true });

  // Pause on hover (desktop preview/testing)
  slider.addEventListener('mouseenter', function () { clearInterval(timer); if (progress) progress.style.animationPlayState = 'paused'; });
  slider.addEventListener('mouseleave', function () { startAuto(); });

  goTo(0);
  startAuto();
})();
</script>
